/**
 * Generate Nashville production-standard credits block HTML for printed sheet music.
 * 
 * Standard Nashville sheet music layout:
 * - Header: Title, Subtitle, Key/Capo/Tempo, Chord Summary
 * - Body: Musical content
 * - Footer: Credits block with Writer, Publisher, Producer, © Copyright, ℗ Phonographic
 * 
 * Page size: 8.5" x 11" (US Letter)
 */

export interface PrintCreditsData {
  subtitle?: string;
  copyright?: string;
  writer?: string;
  publisher?: string;
  producer?: string;
  phonographic?: string;
  ccli?: string;
}

/**
 * Generate the credits/footer HTML block following Nashville production standards.
 * This replaces the simple copyright footer with a full credits block.
 */
export function generateCreditsFooterHtml(credits: PrintCreditsData): string {
  const lines: string[] = [];

  if (credits.writer) {
    lines.push(`<div class="credits-line"><span class="credits-label">Written by:</span> ${escapeHtml(credits.writer)}</div>`);
  }
  if (credits.publisher) {
    lines.push(`<div class="credits-line"><span class="credits-label">Published by:</span> ${escapeHtml(credits.publisher)}</div>`);
  }
  if (credits.producer) {
    lines.push(`<div class="credits-line"><span class="credits-label">Produced by:</span> ${escapeHtml(credits.producer)}</div>`);
  }

  const legalParts: string[] = [];
  if (credits.copyright) {
    legalParts.push(escapeHtml(credits.copyright));
  }
  if (credits.phonographic) {
    legalParts.push(escapeHtml(credits.phonographic));
  }
  if (legalParts.length > 0) {
    lines.push(`<div class="credits-legal">${legalParts.join(" &nbsp;&bull;&nbsp; ")}</div>`);
  }

  if (credits.ccli) {
    lines.push(`<div class="credits-ccli">CCLI Song # ${escapeHtml(credits.ccli)}</div>`);
  }

  if (lines.length === 0) {
    // Fallback to default copyright
    const currentYear = new Date().getFullYear();
    return `<div class="print-footer credits-block">
      <div class="credits-legal">&copy; ${currentYear} Albert LaMotte &middot; Generated by Create Christian Music</div>
    </div>`;
  }

  return `<div class="print-footer credits-block">
    ${lines.join("\n    ")}
  </div>`;
}

/**
 * Generate the subtitle HTML for the header area.
 */
export function generateSubtitleHtml(subtitle?: string): string {
  if (!subtitle) return "";
  return `<div class="print-subtitle">${escapeHtml(subtitle)}</div>`;
}

