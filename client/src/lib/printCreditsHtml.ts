/**
 * Standard @page CSS for 8.5" x 11" (US Letter) with proper margins.
 */
export function getPageSizeCss(
  orientation: "portrait" | "landscape" = "portrait",
  margins?: { top: number; right: number; bottom: number; left: number }
): string {
  const m = margins || { top: 0.5, right: 0.5, bottom: 0.5, left: 0.5 };
  return `
    @page {
      size: 8.5in 11in;
      margin: ${m.top}in ${m.right}in ${m.bottom}in ${m.left}in;
    }
  `;
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
